HCLOUD_LINUX_VARS_FILE = INVENTORIES_DIR / "group_vars" / "hcloud_linux" / "vars.yml"

# A pristine copy of the volume's starting contents, baked at build time,
# used to detect and refresh stale defaults after an image upgrade
# (research.md section 6, FR-047, FR-048).
PRISTINE_DEFAULTS_DIR = ANSIBLE_ROOT / ".inventories-pristine"
IMAGE_VERSION_FILE = ANSIBLE_ROOT / "VERSION"

# Volume state the interface reads but never writes.
VAULT_FILE = INVENTORIES_DIR / "group_vars" / "all" / "vault.yml"
AUTOGEN_INVENTORY_FILE = INVENTORIES_DIR / "hcloud_autogenerated.yml"
KNOWN_HOSTS_FILE = INVENTORIES_DIR / "hcloud_known_hosts"

# Same script ansible.cfg's vault_password_file points every
# ansible-playbook invocation at; webui/vault.py passes it to the
# standalone ansible-vault binary explicitly rather than relying on
# ansible.cfg discovery, so vault reads/writes don't depend on cwd.
VAULT_PASSWORD_SCRIPT = ANSIBLE_ROOT / "scripts" / "echo-vault-password-environment-variable.sh"

# Playbooks this feature drives, unmodified (plan.md "Modified existing
# files" lists the one exception: playbooks/tasks/create/hcloud.yml).
CREATE_VM_PLAYBOOK = ANSIBLE_ROOT / "playbooks" / "create-vm.yml"
CONFIGURE_PROFILE_PLAYBOOK = ANSIBLE_ROOT / "playbooks" / "configure-profile.yml"
DESTROY_VM_PLAYBOOK = ANSIBLE_ROOT / "playbooks" / "destroy-vm.yml"

# Session secrets: discarded after this many seconds of inactivity, on top
# of being discarded on process stop (spec.md Assumptions).
INACTIVITY_TIMEOUT_SECONDS = 30 * 60

# FR-049: local machine only by default. Binding the process itself to
# 127.0.0.1 inside the container would make the container-runtime port
# mapping unreachable, so loopback-only exposure is enforced by the
# compose files publishing the port to 127.0.0.1 on the host (see
# compose.yaml, compose.build.yaml) rather than by this bind address.
DEFAULT_BIND_HOST = os.environ.get("WEBUI_HOST", "0.0.0.0")  # noqa: S104 - see comment above
DEFAULT_BIND_PORT = int(os.environ.get("WEBUI_PORT", "8080"))

# Bounded ring buffer size for run output (research.md section 9).
