"""Paths and defaults for the web frontend.

Every path here is either baked into the image or lives inside the single
mounted volume at ``inventories/``. See specs/017-hcloud-web-frontend/
data-model.md for the storage-tier table this mirrors.
"""

from __future__ import annotations

import os
from pathlib import Path

# Baked into the image (.docker/Dockerfile.web WORKDIR).
ANSIBLE_ROOT = Path(os.environ.get("WEBUI_ANSIBLE_ROOT", "/ansible"))

# The single named volume. Everything the user owns lives under here.
INVENTORIES_DIR = ANSIBLE_ROOT / "inventories"

# Hidden directory holding application state, inside the inventory
# directory Ansible itself scans. Confirmed safe in research.md section 7:
# Ansible skips dot-directories when parsing an inventory directory.
STATE_DIR = INVENTORIES_DIR / ".webui"

SSH_KEY_DIR = STATE_DIR / "ssh"
SSH_PRIVATE_KEY_FILE = SSH_KEY_DIR / "id_ed25519"
SSH_PUBLIC_KEY_FILE = SSH_KEY_DIR / "id_ed25519.pub"

# vault_my_ssh_key_name is a managed field (FR-019: not hand-editable
# through the configuration form), so the interface -- not the user --
# decides what name to register the key under. A distinctive default
# avoids colliding with an unrelated key the user already has in their
# Hetzner account under a generic name like "id_ed25519".
DEFAULT_SSH_KEY_NAME = "ansible-web-frontend"

POOL_FILE = STATE_DIR / "hostname_pool_hcloud.yml"
PRESETS_FILE = STATE_DIR / "presets.json"
SEEDED_VERSION_FILE = STATE_DIR / "seeded-version"

# Server type and location per machine, keyed by hostname. Not part of
# hcloud_autogenerated.yml's schema (that file only ever recorded what an
# SSH connection needs), so the interface tracks these two extra display
# fields itself: written by webui/runner.py when a provisioning run
# succeeds, pruned when a destroy run succeeds. A machine created from the
# command line, outside the interface, simply has no entry here.
MACHINE_DETAILS_FILE = STATE_DIR / "machine_details.json"

# The cost ledger (webui/costs.py): one row per life of a machine, so the
# month's estimate can include machines that no longer exist. SQLite rather
# than a service, for the reasons in that module's docstring; it lives in
# the volume, so it survives a restart and an image upgrade like everything
# else the operator owns.
COST_DB_FILE = STATE_DIR / "costs.sqlite3"

# Repository defaults, baked into the image, read-only at runtime.
DEFAULT_POOL_FILE = ANSIBLE_ROOT / "playbooks" / "vars" / "hostname_pool_hcloud.yml"
VAULT_TEMPLATE_FILE = INVENTORIES_DIR / "group_vars" / "all" / "vault-template.yml"
